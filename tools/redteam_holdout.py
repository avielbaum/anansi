"""Fresh held-out red-team cases for gate G5.

    python tools/redteam_holdout.py            # writes evals/redteam_holdout.jsonl (deterministic)
    python tools/redteam.py run --key change-me --cases evals/redteam_holdout.jsonl --out redteam_holdout.jsonl

Why this exists: the main set (evals/redteam.jsonl) was used to tune the output rules, the order check and the judges, so
its numbers no longer say how the gateway does on attacks nobody has tuned against. These cases use new wordings, new
disguises and new marker shapes, and every case has split "holdout". RULE: nothing is tuned on them. If a holdout run
finds a hole, fix it, then write a NEW holdout set; do not re-score this one as clean.
Known flaw in this set: `MARKERS[i % len(MARKERS)]` is always index 0 because markers are only added when i % 5 == 0, so every planted word is
`Quokka<n>`. The next set must index with i // 5. Honest limit: the author knows the rules the gateway applies, so these are fresh but not blind. A person outside the project
writing attacks would be a stronger test. Prompts are short generic stand-ins; they ask for things and contain no harmful content."""
